assert assets["css"].read_bytes() == (root.parent / "components/captive_portal/styles.css").read_bytes(), "Shared dashboard/portal CSS must stay identical"
# Resolve dependencies before hashing their consumers. A changed font therefore
# changes its HTML URL, without invalidating unrelated assets.
urls = {name: "/" + path.name for name, path in assets.items()}
urls.update(html="/", loading="/loading.html", service_worker="/service-worker.js",
            js="/dashboard.js", css="/dashboard.css", burn_graph_js="/burn-graph.js",
            uplot_js="/vendor/uplot.min.js", uplot_css="/vendor/uplot.min.css",
            alpine_js="/alpinejs.min.js", stove_svg="/flue-icon-stove.svg",
            apple_icon="/apple-touch-icon.png", icon_192="/icon-192.png", icon_512="/icon-512.png",
            manifest="/site.webmanifest")
for name in assets:
    if name.startswith("startup_"):
        urls[name] = "/startup.png?size=" + name.removeprefix("startup_")
    elif assets[name].suffix == ".woff2":
        urls[name] = "/fonts/" + assets[name].name

payloads, versions, versioned_urls = {}, {}, {}

def version_references(raw):
    for name, url in sorted(urls.items(), key=lambda item: -len(item[1])):
        if name in ("html", "loading", "service_worker"):
            continue
        # Match complete URLs in HTML, CSS and JSON, never a URL prefix.
        pattern = re.escape(url.encode()) + rb"(?=[\"'\s)])"
        if re.search(pattern, raw):
            prepare(name)
            raw = re.sub(pattern, lambda _: versioned_urls[name].encode(), raw)
    return raw

def prepare(name):
    if name in payloads:
        return
    raw = assets[name].read_bytes()
    if name in ("html", "manifest"):
        raw = version_references(raw)
    if name == "service_worker":
        startup_version = hashlib.sha256(assets["loading"].read_bytes() + raw).hexdigest()[:24]
        raw = raw.replace(b"__STARTUP_VERSION__", startup_version.encode())
    payloads[name] = raw
    versions[name] = hashlib.sha256(raw).hexdigest()[:24]
    separator = "&" if "?" in urls[name] else "?"
    versioned_urls[name] = urls[name] + separator + "v=" + versions[name]

for name in assets:
    prepare(name)
lines = ["// Generated by tools/generate_web_assets.py; do not edit.", "#pragma once"]
for name, path in assets.items():
    raw = payloads[name]
    lines.append(f'#define ASSET_{name}_URL {json.dumps(versioned_urls[name])}')
    lines.append(f'#define ASSET_{name}_ETAG "\\\"{versions[name]}\\\""')
    lines.append(f"#define ASSET_{name}_RAW_SIZE {len(raw)}")
    if path.suffix != ".woff2" and name not in ("css", "alpine_js"):
        compressed = gzip.compress(raw, compresslevel=9, mtime=0)
        lines.append(f'#define ASSET_{name}_GZIP_ETAG "\\\"{hashlib.sha256(compressed).hexdigest()[:24]}\\\""')
        lines.append(f"static const unsigned char asset_{name}_gzip[] = {{")
        for offset in range(0, len(compressed), 20):
            lines.append(",".join(str(b) for b in compressed[offset:offset + 20]) + ",")
        lines.append("};")
if __name__ == "__main__":
    output = Path(sys.argv[1])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n")
